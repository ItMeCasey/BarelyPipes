"""Writes the resources of one BarelyPipes module: textures, models, item definitions, blockstate, recipes and lang.

Usage: python scripts/make_assets.py <mc> <forge|neoforge> [--check]

Pipe textures come from the approved set in AeroFlux-Pipe-Template/gen (generated by gen_pipes.py); GUI glyphs and
tool icons come from AeroFlux's resources (the same pictures, renamed). Everything else is written here so all ten
modules stay identical apart from the format differences between Minecraft versions:

  26.x    items/<id>.json item definitions, models/item/<id>.json, data/<ns>/recipe/, result {id, count}
  1.21.1  models/item/<id>.json, data/<ns>/recipe/, result {id, count}
  1.20.1  models/item/<id>.json, data/<ns>/recipes/, result {item, count}, tags as {"tag": ...}
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = r"C:\Users\casey\Desktop\AeroFlux-Pipe-Template"
AF = r"C:\Users\casey\Desktop\AeroFlux\versions"
MODID = "barelypipes"
TIERS = ["iron", "gold", "diamond"]
TIERED = ["fluid", "item", "energy", "gas"]
UNTIERED = ["redstone", "me", "dense_me", "storage"]
PARTS = ["arm_v", "arm_h", "arm_end", "core_v", "core_h", "core_end", "plug_v", "plug_h", "plug"]
ARM_LENGTH = 10.0

NAMES = {"fluid": "Fluid", "item": "Item", "energy": "Energy", "gas": "Gas", "redstone": "Redstone", "me": "ME",
         "dense_me": "Dense ME", "storage": "Storage"}


def family(mc):
    return "26" if mc.startswith("26") else mc


def pipe_ids():
    ids = []
    for t in TIERED:
        for tier in TIERS:
            ids.append((f"{tier}_{t}_pipe", t, tier))
    for t in UNTIERED:
        ids.append((f"{t}_pipe", t, None))
    return ids


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def ref(namespace_path):
    return f"{MODID}:{namespace_path}"


def item_model(kind, tier):
    """A straight pipe along x for the inventory icon: two arms and a core, textured like the bundle model."""
    def tex(part):
        return ref("block/pipe_" + kind + "_" + part + (f"_t{TIERS.index(tier) + 1}" if tier else ""))

    textures = {p: tex(p) for p in ("arm_h", "arm_end", "core_h", "core_end")}
    textures["particle"] = textures["core_h"]

    def face(texture, uv):
        return {"uv": uv, "texture": "#" + texture}

    def arm(x0, x1, end_face):
        length = x1 - x0
        span = round(16.0 * length / ARM_LENGTH, 3)
        side = lambda: face("arm_h", [0, 0, span, 16])
        return {
            "from": [x0, 7, 7], "to": [x1, 9, 9],
            "faces": {"north": side(), "south": side(), "up": side(), "down": side(),
                      end_face: face("arm_end", [0, 0, 16, 16])},
        }

    core = {
        "from": [6.5, 6.5, 6.5], "to": [9.5, 9.5, 9.5],
        "faces": {"north": face("core_h", [0, 0, 16, 16]), "south": face("core_h", [0, 0, 16, 16]),
                  "up": face("core_h", [0, 0, 16, 16]), "down": face("core_h", [0, 0, 16, 16]),
                  "west": face("core_end", [0, 0, 16, 16]), "east": face("core_end", [0, 0, 16, 16])},
    }
    return {
        "gui_light": "side",
        "textures": textures,
        "elements": [arm(0, 6.5, "west"), core, arm(9.5, 16, "east")],
        "display": {
            "gui": {"rotation": [30, 225, 0], "translation": [0, 0, 0], "scale": [0.625, 0.625, 0.625]},
            "ground": {"rotation": [0, 0, 0], "translation": [0, 3, 0], "scale": [0.25, 0.25, 0.25]},
            "fixed": {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [0.5, 0.5, 0.5]},
            "thirdperson_righthand": {"rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.375, 0.375, 0.375]},
            "firstperson_righthand": {"rotation": [0, 45, 0], "translation": [0, 0, 0], "scale": [0.4, 0.4, 0.4]},
            "firstperson_lefthand": {"rotation": [0, 225, 0], "translation": [0, 0, 0], "scale": [0.4, 0.4, 0.4]},
        },
    }


FLAT_ITEMS = ["pipe_wrench", "conduit_tool", "speed_upgrade", "capacity_upgrade", "filter_upgrade", "priority_upgrade"]


def recipes(fam):
    """Recipes as (name, builder(fam) -> json). Vanilla ingredients only, so no loader tag differences."""
    def ing(item):
        if fam != "26":
            return {"item": item}
        return item

    def result(item, count=1):
        if fam == "1.20.1":
            return {"item": f"{MODID}:{item}", "count": count}
        return {"id": f"{MODID}:{item}", "count": count}

    def shaped(pattern, key, out, count=1, category="misc"):
        data = {"type": "minecraft:crafting_shaped", "category": category,
                "key": {k: ing(v) for k, v in key.items()}, "pattern": pattern, "result": result(out, count)}
        return data

    out = {}
    base = {"iron": "minecraft:iron_ingot", "gold": "minecraft:gold_ingot", "diamond": "minecraft:diamond"}
    carrier = {"item": "minecraft:copper_ingot", "fluid": "minecraft:glass", "energy": "minecraft:redstone",
               "gas": "minecraft:amethyst_shard"}
    for t in TIERED:
        for tier in TIERS:
            out[f"{tier}_{t}_pipe"] = shaped(["TTT", "CCC", "TTT"], {"T": base[tier], "C": carrier[t]},
                                             f"{tier}_{t}_pipe", 6)
    out["redstone_pipe"] = shaped(["III", "RRR", "III"], {"I": "minecraft:iron_ingot", "R": "minecraft:redstone"},
                                  "redstone_pipe", 6, "redstone")
    out["storage_pipe"] = shaped(["III", "EEE", "III"], {"I": "minecraft:iron_ingot", "E": "minecraft:emerald"},
                                 "storage_pipe", 6)
    out["pipe_wrench"] = shaped(["I I", " R ", " I "], {"I": "minecraft:iron_ingot", "R": "minecraft:redstone"},
                                "pipe_wrench", 1, "equipment")
    out["conduit_tool"] = shaped(["I I", " D ", " I "], {"I": "minecraft:iron_ingot", "D": "minecraft:diamond"},
                                 "conduit_tool", 1, "equipment")
    out["speed_upgrade"] = shaped(["RGR", "RQR", "RGR"], {"R": "minecraft:redstone", "G": "minecraft:gold_ingot",
                                                          "Q": "minecraft:quartz"}, "speed_upgrade")
    out["capacity_upgrade"] = shaped(["RGR", "RCR", "RGR"], {"R": "minecraft:redstone", "G": "minecraft:gold_ingot",
                                                             "C": "minecraft:chest"}, "capacity_upgrade")
    out["filter_upgrade"] = shaped(["IPI", "PHP", "IPI"], {"I": "minecraft:iron_ingot", "P": "minecraft:paper",
                                                           "H": "minecraft:hopper"}, "filter_upgrade")
    out["priority_upgrade"] = shaped(["IPI", "PCP", "IPI"], {"I": "minecraft:iron_ingot", "P": "minecraft:paper",
                                                             "C": "minecraft:comparator"}, "priority_upgrade")
    return out


def conditional(data, loader, fam, modid):
    """Adds the mod-loaded condition for recipes that need another mod."""
    if loader == "neoforge" and fam != "1.20.1":
        data = {"neoforge:conditions": [{"type": "neoforge:mod_loaded", "modid": modid}], **data}
    elif loader == "neoforge":
        data = {"conditions": [{"type": "forge:mod_loaded", "modid": modid}], **data}
    elif fam == "26":
        # Forge 26.x wraps a conditional recipe in a forge:conditional entry.
        data = {"type": "forge:conditional", "forge:condition": {"type": "forge:mod_loaded", "modid": modid},
                "recipes": [{"recipe": data}]}
    else:
        data = {"conditions": [{"type": "forge:mod_loaded", "modid": modid}], **data}
    return data


def ae_recipes(fam):
    def ing(item):
        return {"item": item} if fam != "26" else item

    def result(item, count=1):
        return {"item": f"{MODID}:{item}", "count": count} if fam == "1.20.1" else {"id": f"{MODID}:{item}", "count": count}

    me = {"type": "minecraft:crafting_shaped", "category": "misc",
          "key": {"C": ing("minecraft:copper_ingot"), "D": ing("minecraft:glowstone_dust"),
                  "X": ing("minecraft:amethyst_shard")},
          "pattern": ["CCC", "DXD", "CCC"], "result": result("me_pipe", 8)}
    dense_in = [ing(f"{MODID}:me_pipe")] * 4 + [ing("minecraft:glowstone_dust"), ing("minecraft:redstone")]
    dense = {"type": "minecraft:crafting_shapeless", "category": "misc", "ingredients": dense_in,
             "result": result("dense_me_pipe")}
    return {"me_pipe": me, "dense_me_pipe": dense}


HINT_SUFFIXES = (".tooltip",)
HINT_KEYS = (f"screen.{MODID}.pipe_config.endpoint_empty", f"screen.{MODID}.pipe_config.endpoint_installed",
             f"screen.{MODID}.pipe_config.filter_slot.clear", f"screen.{MODID}.pipe_config.filter_slot.fluid",
             f"screen.{MODID}.pipe_config.filter_slot.item", f"gui.{MODID}.upgrades.hint")
HINT_TEXTS = {
    f"message.{MODID}.tool_run_start": "Run started on a %s pipe",
    f"message.{MODID}.tool_paste_run_start": "Run started",
}


def strip_hints(out):
    """No hints (Casey, 2026-11-13): the explanatory tooltips, the click instructions and the usage sentences are not in the game."""
    for k in list(out):
        if k in HINT_KEYS or (k.endswith(HINT_SUFFIXES) and not k.startswith("tooltip." + MODID + ".tool_mode")):
            del out[k]
    out.update({k: v for k, v in HINT_TEXTS.items() if k in out})


def lang():
    af = os.path.join(AF, "mc26.1.2", "neoforge", "src", "generated", "resources", "assets", "aeroflux", "lang", "en_us.json")
    src = json.load(open(af, encoding="utf-8"))
    keep = ("message.aeroflux.endpoint_upgrade", "message.aeroflux.pipe_", "message.aeroflux.protected", "message.aeroflux.tool_",
            "message.aeroflux.upgrade_", "connection_mode.", "distribution_mode.", "tool_mode.aeroflux", "tooltip.aeroflux.tool_mode",
            "screen.aeroflux.pipe_config", "pipe.aeroflux.", "upgrade.aeroflux.speed", "upgrade.aeroflux.capacity",
            "upgrade.aeroflux.filter", "upgrade.aeroflux.priority", "tooltip.aeroflux.look.upgrades")
    out = {}
    for k, v in src.items():
        if any(k.startswith(p) for p in keep):
            out[k.replace("aeroflux", MODID)] = v.replace("AeroFlux", "Barely Pipes")
    strip_hints(out)
    out[f"itemGroup.{MODID}"] = "Barely Pipes"
    out[f"block.{MODID}.conduit_bundle"] = "Pipe Bundle"
    out[f"pipe.{MODID}.storage"] = "Storage"
    out[f"item.{MODID}.pipe_wrench"] = "Pipe Wrench"
    out[f"item.{MODID}.conduit_tool"] = "Conduit Tool"
    out[f"item.{MODID}.speed_upgrade"] = "Speed Upgrade"
    out[f"item.{MODID}.capacity_upgrade"] = "Capacity Upgrade"
    out[f"item.{MODID}.filter_upgrade"] = "Filter Upgrade"
    out[f"item.{MODID}.priority_upgrade"] = "Priority Upgrade"
    for pid, kind, tier in pipe_ids():
        label = NAMES[kind] + " Pipe"
        out[f"item.{MODID}.{pid}"] = (tier.capitalize() + " " + label) if tier else label
    # Side names (the wrench message, the tool and the look-at overlays use them).
    for face in ("down", "up", "north", "south", "west", "east"):
        out.setdefault(f"face.{MODID}.{face}", face.capitalize())
    # Look-at overlays (Show Me What This Is): the pipe under the crosshair, built by core/conduit/PipeLookInfo.
    for key, text in [
        ("arm", "Arm: %s side"), ("plug", "Plug: %s side"), ("core", "Core of the pipe"),
        ("junction", "Junction of the bundle"), ("mode", "Mode: %s"), ("connected_to", "Connected to: %s"),
        ("another_bundle", "another bundle"), ("a_machine", "a machine"), ("not_connected", "Not connected"),
        ("sides", "Sides: %s"), ("side_mode", "%s (%s)"), ("no_sides", "No side is connected"),
        ("throughput", "Throughput: %s"), ("distribution", "Distribution: %s"),
        ("filter_whitelist", "Filter: whitelist, %s listed"), ("filter_blacklist", "Filter: blacklist, %s listed"),
        ("filter_whitelist_empty", "Filter: whitelist, empty"),
        ("filter_blacklist_empty", "Filter: blacklist, empty"),
        ("priority", "Priority: %s"), ("others", "Also in this bundle: %s"), ("pipes", "Pipes: %s"),
    ]:
        out[f"smwti.{MODID}.{key}"] = text
    # Jade asks for a name for every plugin in its config screen (and asserts on it in dev).
    out[f"config.jade.plugin_{MODID}.pipe_look"] = "Pipe details"
    for k in list(out):
        if "wrench" in k:
            out[k] = out[k].replace("Flux Wrench", "Pipe Wrench")
    return dict(sorted(out.items()))


def main(mc, loader):
    fam = family(mc)
    mod = os.path.join(ROOT, f"{loader}-{mc}")
    res = os.path.join(mod, "src", "main", "resources")
    common = os.path.join(ROOT, "common", "src", "main", "resources")
    assets = os.path.join(common, "assets", MODID)  # shared by every module: textures, glyphs, item models, lang
    mod_assets = os.path.join(res, "assets", MODID)  # per module: the blockstate (loader specific)
    data = os.path.join(res, "data", MODID)
    # textures
    tdir = os.path.join(assets, "textures", "block")
    os.makedirs(tdir, exist_ok=True)
    gen = os.path.join(TEMPLATE, "gen")
    for f in os.listdir(gen):
        if f.startswith("pipe_") and f.endswith(".png"):
            shutil.copyfile(os.path.join(gen, f), os.path.join(tdir, f))
    afres = os.path.join(AF, f"mc{mc}" if f"mc{mc}" in os.listdir(AF) else "mc26.1.2", loader, "src", "main", "resources", "assets", "aeroflux")
    shutil.copyfile(os.path.join(afres, "textures", "block", "pipe_node.png"), os.path.join(tdir, "pipe_node.png"))
    gdir = os.path.join(assets, "textures", "gui", "glyph")
    os.makedirs(gdir, exist_ok=True)
    for g in os.listdir(os.path.join(afres, "textures", "gui", "glyph")):
        if g.startswith(("flux_", "sky_", "weather")):
            continue
        shutil.copyfile(os.path.join(afres, "textures", "gui", "glyph", g), os.path.join(gdir, g))
    shutil.copyfile(os.path.join(TEMPLATE, "glyphs", "storage.png"), os.path.join(gdir, "storage.png"))
    # The plug arrow faces, the dark gas glyph face and the 13 by 13 storage glyph are drawn over the template's files.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import gen_plug_arrows
    gen_plug_arrows.main()
    idir = os.path.join(assets, "textures", "item")
    os.makedirs(idir, exist_ok=True)
    for name, srcname in [("pipe_wrench", "flux_wrench"), ("conduit_tool", "conduit_tool"), ("speed_upgrade", "speed_upgrade"),
                          ("capacity_upgrade", "capacity_upgrade"), ("filter_upgrade", "filter_upgrade"),
                          ("priority_upgrade", "priority_upgrade")]:
        shutil.copyfile(os.path.join(afres, "textures", "item", srcname + ".png"), os.path.join(idir, name + ".png"))
    # blockstate: the loaders differ, so copy AeroFlux's and rename
    bs = open(os.path.join(afres, "blockstates", "conduit_bundle.json"), encoding="utf-8").read().replace("aeroflux", MODID)
    os.makedirs(os.path.join(mod_assets, "blockstates"), exist_ok=True)
    open(os.path.join(mod_assets, "blockstates", "conduit_bundle.json"), "w", encoding="utf-8", newline="\n").write(bs)
    if fam != "26" or loader == "forge":
        # Geometry-loader builds (Forge 26.x, and every 1.20.1 and 1.21.1 build) load the bundle through a block model file.
        write_json(os.path.join(mod_assets, "models", "block", "conduit_bundle.json"),
                   {"loader": ref("conduit_bundle"), "textures": {"node": ref("block/pipe_node"), "particle": ref("block/pipe_node")}})
    # item models and definitions
    for pid, kind, tier in pipe_ids():
        write_json(os.path.join(assets, "models", "item", pid + ".json"), item_model(kind, tier))
        if fam == "26":
            write_json(os.path.join(assets, "items", pid + ".json"),
                       {"model": {"type": "minecraft:model", "model": ref("item/" + pid)}})
    for name in FLAT_ITEMS:
        parent = "minecraft:item/handheld" if name in ("pipe_wrench", "conduit_tool") else "minecraft:item/generated"
        write_json(os.path.join(assets, "models", "item", name + ".json"),
                   {"parent": parent, "textures": {"layer0": ref("item/" + name)}})
        if fam == "26":
            write_json(os.path.join(assets, "items", name + ".json"),
                       {"model": {"type": "minecraft:model", "model": ref("item/" + name)}})
    # lang
    write_json(os.path.join(assets, "lang", "en_us.json"), lang())
    # recipes
    rdir = os.path.join(data, "recipes" if fam == "1.20.1" else "recipe")
    shutil.rmtree(rdir, ignore_errors=True)
    for name, body in recipes(fam).items():
        if name == "storage_pipe" and fam in ("1.20.1", "1.21.1"):
            continue  # BarelyStorage has no build for these Minecraft versions: the pipe stays uncraftable
        write_json(os.path.join(rdir, name + ".json"), body)
    if not (loader == "forge" and mc == "1.21.1"):  # AE2 has no Forge build for 1.21.1, so its ME pipes get no recipe there
        for name, body in ae_recipes(fam).items():
            write_json(os.path.join(rdir, name + ".json"), conditional(body, loader, fam, "ae2"))
    print("assets written for", mod)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
